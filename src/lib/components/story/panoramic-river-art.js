// Open the upper basin into a shared paper pocket for the two photographs.
// This moves the painted banks and every current together, preserving their
// individual contours and the exact river mouths at both panorama boundaries.
function openBasin(path) {
  return path.replace(/(-?\d*\.?\d+)[ ,]+(-?\d*\.?\d+)/g, (_, rawX, rawY) => {
    const x = Number(rawX), y = Number(rawY);
    const across = Math.max(0, Math.min(1, (x - 180) / 270, (1360 - x) / 170));
    const rightBasin = Math.max(0, Math.min(1, (x - 740) / 110, (1330 - x) / 180));
    const reach = Math.max(0, Math.min(1, (y - 170) / 100, (840 - y) / 540));
    let bankY = y + across * reach * (155 + rightBasin * 145);
    if (y > 220 && y < 400) bankY += rightBasin * Math.max(0, 550 + (y - 220) * .3 - bankY);
    return `${x} ${+bankY.toFixed(2)}`;
  });
}
